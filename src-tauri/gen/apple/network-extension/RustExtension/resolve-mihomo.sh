#!/bin/sh
# Phase "Resolve Rust kernel" of BillowRust (project.yml).
#
# Finds the libapp.a copy produced by tool/ios/build.sh (archive with the
# billow_ios_vpn_* exports of src-tauri/src/ios_vpn.rs) and publishes the
# build inputs:
#   $SRCROOT/build/rust-kernel/linked.xcconfig   OTHER_LDFLAGS = -force_load <archive>
#   BILLOW_RUST_KERNEL_LINKED=1 (xcconfig constant) when the archive contains
#   billow_ios_vpn_start.
# Without the archive the extension still builds and reports
# engineNotAvailable (code 4) through the start path. Exit status is always 0.
set -euo pipefail
cd "${SRCROOT:-.}"
archive=$(sh network-extension/RustExtension/resolve-symbol.sh || true)
mkdir -p build/rust-kernel
flags_file="$PWD/build/rust-kernel/linked.xcconfig"
linked_file="$PWD/build/rust-kernel/linked.constant"
write_unlinked() {
  cat > "$flags_file" <<'XCCONFIG'
// Generated by network-extension/RustExtension/resolve-mihomo.sh.
// libapp.a with billow_ios_vpn_* not linked: engineNotAvailable path.
BILLOW_RUST_KERNEL_LINKED = 0
BILLOW_RUST_KERNEL_DEFINES = $(inherited)
BILLOW_RUST_KERNEL_SWIFT_FLAGS = $(inherited)
OTHER_LDFLAGS = $(inherited)
XCCONFIG
  printf 'BILLOW_RUST_KERNEL_LINKED = 0\n' > "$linked_file"
}
# Rust staticlibs are often built by a newer LLVM than Xcode's nm understands;
# a grep over the archive's symbol indexes is enough for this presence check.
if [ -n "$archive" ] && (LC_ALL=C grep -aq "billow_ios_vpn_start" "$archive" 2>/dev/null); then
  {
    echo '// Generated by network-extension/RustExtension/resolve-mihomo.sh.'
    # Quote the path: Externals lives under the checkout, which may contain
    # spaces.
    printf 'OTHER_LDFLAGS = $(inherited) -force_load "%s"\n' "$archive"
    echo 'BILLOW_RUST_KERNEL_LINKED = 1'
    echo 'BILLOW_RUST_KERNEL_DEFINES = $(inherited) BILLOW_RUST_KERNEL_LINKED=1'
    echo 'BILLOW_RUST_KERNEL_SWIFT_FLAGS = $(inherited) -D BILLOW_RUST_KERNEL_LINKED'
  } > "$flags_file"
  printf 'BILLOW_RUST_KERNEL_LINKED = 1\n' > "$linked_file"
  echo "BillowRust: linking Rust kernel $archive"
else
  write_unlinked
  echo "BillowRust: libapp.a with billow_ios_vpn_* not found; engineNotAvailable path active"
fi
